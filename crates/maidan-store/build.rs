//! Derives the migration register from `migrations/{postgres,sqlite}`.
//!
//! Every `NNNN_<slug>.sql` file is a migration with version `NNNN`, applied in
//! version order. `*_down.sql` files are manual teardown scripts and are never
//! applied. A name without a four-digit version, or two files with one
//! version, fails the build rather than being skipped.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() -> Result<(), String> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").map_err(|e| e.to_string())?);
    let root = manifest.join("../../migrations");
    let mut out = String::from("// Generated by maidan-store's build.rs from migrations/.\n");
    for (dialect, name) in [
        ("postgres", "POSTGRES_MIGRATIONS"),
        ("sqlite", "SQLITE_MIGRATIONS"),
    ] {
        let dir = root.join(dialect);
        println!("cargo:rerun-if-changed={}", dir.display());
        let files = register(&dir)?;
        writeln!(out, "const {name}: &[Migration] = &[").map_err(|e| e.to_string())?;
        for (version, file) in files {
            let path = dir.join(&file);
            println!("cargo:rerun-if-changed={}", path.display());
            writeln!(
                out,
                "    Migration {{ version: {version}, file: {file:?}, sql: include_str!({:?}) }},",
                path.display().to_string()
            )
            .map_err(|e| e.to_string())?;
        }
        out.push_str("];\n");
    }
    let dest =
        PathBuf::from(std::env::var("OUT_DIR").map_err(|e| e.to_string())?).join("migrations.rs");
    std::fs::write(&dest, out).map_err(|e| format!("write {}: {e}", dest.display()))
}

fn register(dir: &Path) -> Result<Vec<(i64, String)>, String> {
    let entries = std::fs::read_dir(dir).map_err(|e| format!("read {}: {e}", dir.display()))?;
    let mut files = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|e| e.to_string())?;
        let file = entry.file_name().to_string_lossy().into_owned();
        if !file.ends_with(".sql") || file.ends_with("_down.sql") {
            continue;
        }
        let version = file
            .get(..4)
            .filter(|digits| digits.bytes().all(|b| b.is_ascii_digit()))
            .filter(|_| file.as_bytes().get(4) == Some(&b'_'))
            .and_then(|digits| digits.parse::<i64>().ok())
            .ok_or_else(|| format!("{}: {file} is not NNNN_<slug>.sql", dir.display()))?;
        files.push((version, file));
    }
    files.sort();
    if let Some(pair) = files.windows(2).find(|pair| pair[0].0 == pair[1].0) {
        return Err(format!(
            "{}: {} and {} share version {}",
            dir.display(),
            pair[0].1,
            pair[1].1,
            pair[0].0
        ));
    }
    Ok(files)
}
