#!/usr/bin/env python3
"""Write each crate's single integration-test binary root, tests/it/main.rs.

Cargo builds and links every tests/*.rs as its own binary. maidan-server had
over 300 of them, each statically linking the whole server, so the integration
job spent most of its time in the linker. The crates listed here set
`autotests = false` and build one `it` binary instead, whose main.rs declares
every tests/*.rs as a module in place (`#[path = "../x.rs"] mod x;`). A test's
name becomes `x::test_name`, so

    cargo nextest run -p maidan-server -E 'test(/^x::/)'
    cargo test -p maidan-server --test it x::

run what `--test x` used to. The files stay where they are, so their own
`mod common;` and `include_str!` paths are unchanged.

    scripts/gen-integration-main.py           rewrite every tests/it/main.rs
    scripts/gen-integration-main.py --check   exit 1 if one is out of date

The binary also tests itself: a tests/*.rs file that main.rs does not declare
fails `it_declares_every_test_file`, so a new file cannot be skipped silently.
A file in OWN_BINARY stays its own [[test]] target instead.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRATES = ["maidan-server", "maidan-store", "maidan-search", "maidan-mcp"]
# Test files that stay their own binary, each with a [[test]] entry in the
# crate's Cargo.toml. bootstrap_absent_e2e runs under --no-default-features,
# which the rest of the suite was never written to build under.
# maidan-search's sqlite_vec files need the sqlite-vec feature
# (required-features), which the default build of `it` leaves out.
OWN_BINARY = {
    "maidan-server": {"bootstrap_absent_e2e.rs"},
    "maidan-search": {"sqlite_vec.rs", "sqlite_vec_pre_registration.rs"},
}

HEADER = """\
// @generated by scripts/gen-integration-main.py; do not edit by hand.
//
// One integration-test binary for this crate instead of one per tests/*.rs,
// so the crate links once. Each file is a module named after it: run one with
// `cargo nextest run -p {krate} -E 'test(/^file_name::/)'`.
//
// Each file keeps its own `mod common;`, so the shared helpers compile once
// per file that uses them, as they did when every file was its own binary.
#![allow(clippy::duplicate_mod)]
"""

GUARD = """
/// A tests/*.rs file this binary does not declare would never build or run.
#[test]
fn it_declares_every_test_file() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests");
    let main = include_str!("main.rs");
    let mut missing = Vec::new();
    for entry in std::fs::read_dir(&dir).into_iter().flatten().flatten() {
        let path = entry.path();
        if path.extension().is_some_and(|e| e == "rs") {
            let name = entry.file_name().to_string_lossy().into_owned();
            let own_binary: &[&str] = &[__OWN__];
            if !own_binary.contains(&name.as_str())
                && !main.contains(&format!("#[path = \\"../{name}\\"]"))
            {
                missing.push(name);
            }
        }
    }
    assert!(
        missing.is_empty(),
        "run scripts/gen-integration-main.py: tests/it/main.rs does not declare {missing:?}"
    );
}
"""


def render(krate: str) -> str:
    own = OWN_BINARY.get(krate, set())
    tests = sorted(p.name for p in (ROOT / "crates" / krate / "tests").glob("*.rs") if p.name not in own)
    lines = [HEADER.format(krate=krate)]
    for name in tests:
        lines.append(f'#[path = "../{name}"]\nmod {name[:-3]};\n')
    return "\n".join(lines) + GUARD.replace("__OWN__", ", ".join(f'"{n}"' for n in sorted(own)))


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for krate in CRATES:
        out = ROOT / "crates" / krate / "tests" / "it" / "main.rs"
        want = render(krate)
        have = out.read_text() if out.exists() else None
        if have == want:
            continue
        if check:
            stale.append(str(out.relative_to(ROOT)))
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(want)
            print(f"wrote {out.relative_to(ROOT)}")
    for s in stale:
        print(f"{s} is out of date: run scripts/gen-integration-main.py", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
