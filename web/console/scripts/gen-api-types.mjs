// Generates src/core/api.gen.ts from the server's committed OpenAPI spec.
//   node scripts/gen-api-types.mjs          write the file
//   node scripts/gen-api-types.mjs --check  exit 1 if the committed file is stale
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
export const SPEC = resolve(here, "../../../crates/maidan-server/tests/fixtures/wire/openapi.json");
export const OUT = resolve(here, "../src/core/api.gen.ts");

const ident = (n) => n.replace(/[^A-Za-z0-9_]/g, "_");

/** Schema $refs must stay under components/schemas with a safe type name. */
export function isSafeSchemaRef(ref) {
  return typeof ref === "string" && /^#\/components\/schemas\/[A-Za-z_][A-Za-z0-9_]*$/.test(ref);
}

/** Path templates with empty, `.`, or `..` segments are not mintable API routes. */
export function isSafePathTemplate(path) {
  if (typeof path !== "string" || !path.startsWith("/")) return false;
  if (path.includes("?") || path.includes("#")) return false;
  const parts = path.split("/");
  return parts.slice(1).every((seg) => seg !== "" && seg !== "." && seg !== "..");
}

const key = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k));

export function tsType(s) {
  if (s === true || s == null || (typeof s === "object" && Object.keys(s).length === 0)) return "unknown";
  if (s.$ref) {
    if (!isSafeSchemaRef(s.$ref)) return "unknown";
    return ident(s.$ref.split("/").pop());
  }
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  for (const k of ["oneOf", "anyOf"]) if (s[k]) return s[k].map((x) => wrap(tsType(x))).join(" | ");
  if (s.allOf) return s.allOf.map((x) => wrap(tsType(x))).join(" & ");
  const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : s.properties ? ["object"] : [];
  if (types.length === 0) return "unknown";
  return types.map((t) => wrap(one(t, s))).join(" | ");
}
const wrap = (t) => (/[|&]/.test(t) && !/^\{[\s\S]*\}$/.test(t) ? `(${t})` : t);
function one(t, s) {
  switch (t) {
    case "null": return "null";
    case "string": return "string";
    case "integer": case "number": return "number";
    case "boolean": return "boolean";
    case "array": return `${wrap(tsType(s.items))}[]`;
    case "object": {
      const req = new Set(s.required ?? []);
      const props = Object.entries(s.properties ?? {}).map(([k, v]) => `${key(k)}${req.has(k) ? "" : "?"}: ${tsType(v)};`);
      if (s.additionalProperties && s.additionalProperties !== false) props.push(`[k: string]: ${s.additionalProperties === true ? "unknown" : tsType(s.additionalProperties)};`);
      return props.length ? `{ ${props.join(" ")} }` : "Record<string, unknown>";
    }
    default: return "unknown";
  }
}

const METHODS = ["get", "post", "put", "patch", "delete"];
export function routes(spec) {
  const out = [];
  const paths = spec.paths && typeof spec.paths === "object" ? spec.paths : {};
  for (const p of Object.keys(paths)) {
    if (!isSafePathTemplate(p)) continue;
    if (!Object.prototype.hasOwnProperty.call(paths, p)) continue;
    const item = paths[p];
    if (!item || typeof item !== "object") continue;
    for (const m of METHODS) if (Object.prototype.hasOwnProperty.call(item, m) && item[m]) out.push(`${m.toUpperCase()} ${p}`);
  }
  return out.sort();
}

export function generate(spec) {
  const lines = ["// Generated by scripts/gen-api-types.mjs from crates/maidan-server/tests/fixtures/wire/openapi.json.", "// Do not edit. Run `npm run gen:api` after the spec changes.", ""];
  const schemas = spec.components?.schemas && typeof spec.components.schemas === "object" ? spec.components.schemas : {};
  for (const name of Object.keys(schemas).sort((a, b) => a.localeCompare(b))) {
    if (!Object.prototype.hasOwnProperty.call(schemas, name)) continue;
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) continue;
    lines.push(`export type ${ident(name)} = ${tsType(schemas[name])};`);
  }
  lines.push("", "/** Every METHOD + path template the server documents. */", "export type ApiRoute =");
  for (const r of routes(spec)) lines.push(`  | ${JSON.stringify(r)}`);
  lines.push(";", "");
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate(JSON.parse(readFileSync(SPEC, "utf8")));
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) { console.error("api.gen.ts is stale: run `npm run gen:api`"); process.exit(1); }
    console.log("api.gen.ts matches the spec");
  } else { writeFileSync(OUT, text); console.log(`wrote ${OUT}`); }
}
